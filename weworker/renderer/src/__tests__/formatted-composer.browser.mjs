// Isolated composer fixture; no real desktop or business writes.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core')
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 850 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('http://127.0.0.1:8765/**', route => route.fulfill({ status: 200, body: '{}', contentType: 'application/json' }))
  await page.goto(`${process.env.FORMATTED_TEST_URL || 'http://127.0.0.1:5187'}/src/__tests__/fixtures/formatted-composer.html`)
  const input = page.locator('textarea[data-weworker-chat-input]')
  const format = page.getByLabel('格式', { exact: true })
  const card = page.getByRole('region', { name: '发布正文', exact: true })
  const send = page.getByRole('button', { name: '发送消息', exact: true })
  const attach = async () => { await format.click(); await page.getByRole('button', { name: '用作发布正文' }).click() }
  const switchTo = async target => { await page.evaluate(value => window.switchDraft(value), target); await page.waitForFunction(value => window.fixtureState.target === value, target) }
  await input.waitFor()
  assert.equal(await format.count(), 0)
  await input.fill('**手写格式**')
  assert.equal(await format.count(), 1)
  await input.fill('普通文字')
  assert.equal(await format.count(), 0)
  await input.fill('普通聊天')
  assert.equal(await page.getByRole('button', { name: '用作发布正文' }).isVisible(), false)
  await input.press('Enter')
  assert.equal(await page.evaluate(() => window.lastSent.text), '普通聊天')
  assert.equal(await page.evaluate(() => window.saveCount), 0)

  await input.evaluate(element => {
    const data = new DataTransfer()
    data.setData('text/html', '<p>上周工作：</p><p><strong>【项目一】</strong></p><ul><li>完成页面开发</li><li>优化详情<ul><li>保留嵌套列表</li></ul></li></ul><ol><li>整理说明</li></ol>')
    data.setData('text/plain', '上周工作：\n完成页面开发')
    element.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
  })
  const markdown = await input.inputValue()
  await format.click()
  await page.getByRole('button', { name: '预览消息排版', exact: true }).click()
  const preview = page.getByLabel('消息排版预览')
  assert.equal(await preview.locator('ul ul').count(), 1)
  const previewHTML = await preview.innerHTML()
  await page.getByRole('button', { name: '返回编辑消息', exact: true }).click()
  await attach()
  await card.waitFor()
  assert.equal(await page.evaluate(() => window.savedBody.content), previewHTML)
  assert.equal(await input.inputValue(), '')
  assert.equal(await page.getByText('正文格式已保存在附件中。请输入发布目标或其他要求。').count(), 0)
  await input.fill('发布到指定任务')
  if (process.env.FORMATTED_SCREENSHOT) await page.screenshot({ path: process.env.FORMATTED_SCREENSHOT })
  await card.getByRole('button', { name: '移回输入框' }).click()
  assert.equal(await card.count(), 0)
  assert.equal(await input.inputValue(), '发布到指定任务\n\n' + markdown)
  assert.equal(await page.getByRole('status').count(), 0)

  await input.fill(markdown)
  await attach()
  await card.waitFor()
  await input.fill('目标指令')
  await card.getByRole('button', { name: '编辑正文', exact: true }).click()
  await page.getByLabel('编辑发布正文').fill('- 修改后的正文')
  assert(await send.isDisabled())
  await switchTo('b')
  await input.fill('其他对话')
  assert.equal(await card.count(), 0)
  await switchTo('a')
  assert.equal(await page.getByLabel('编辑发布正文').inputValue(), '- 修改后的正文')
  assert.equal(await input.inputValue(), '目标指令')
  await card.getByRole('button', { name: '取消修改' }).click()
  assert.equal(await card.getByText('完成页面开发', { exact: true }).count(), 1)
  await card.getByRole('button', { name: '编辑正文', exact: true }).click()
  await page.getByLabel('编辑发布正文').fill('- 修改后的正文')
  await card.getByRole('button', { name: '保存正文', exact: true }).click()
  await card.getByText('修改后的正文', { exact: true }).waitFor()
  assert.equal(await input.inputValue(), '目标指令')
  assert.equal(await page.evaluate(() => window.savedBody['markdown-content']), '- 修改后的正文')
  await input.press('Enter')
  assert.equal(await page.evaluate(() => window.lastSent.files[0].formattedBody.markdown), '- 修改后的正文')
  assert.equal(await card.count(), 0)

  await input.fill('- 保存失败时保留')
  await page.evaluate(() => { window.failSave = true })
  await attach()
  await page.getByRole('status').getByText('fixture save failure').waitFor()
  assert.equal(await input.inputValue(), '- 保存失败时保留')
  assert.equal(await card.count(), 0)
  await page.evaluate(() => { window.failSave = false; window.delaySave = true })
  await format.click()
  const count = await page.evaluate(() => window.saveCount)
  await page.getByRole('button', { name: '用作发布正文' }).evaluate(element => { element.click(); element.click() })
  await page.waitForFunction(() => typeof window.finishSave === 'function')
  assert.equal(await page.evaluate(() => window.saveCount), count + 1)
  await switchTo('b')
  assert.equal(await input.inputValue(), '其他对话')
  await page.evaluate(() => { window.finishSave(); window.delaySave = false })
  await switchTo('a')
  assert.equal(await input.inputValue(), '- 保存失败时保留')
  assert.equal(await card.count(), 0)
  assert.equal(await page.getByRole('status').count(), 0)

  await page.getByRole('button', { name: '上传文件', exact: true }).click()
  await page.getByText('note.txt', { exact: true }).waitFor()
  await page.getByRole('button', { name: '移除文件', exact: true }).click()
  assert.equal(await input.inputValue(), '- 保存失败时保留')
  await input.fill('!echo sample')
  assert.equal(await format.count(), 0)
  await input.press('Enter')
  assert.equal(await page.evaluate(() => window.lastShell), 'echo sample')
  assert.deepEqual(errors, [])
  console.log('PASS: ordinary chat, rich paste, preview, card restore, edit/cancel/save, send, draft switching, save failure, duplicate click, stale completion, ordinary attachments and command input')
} finally { await browser.close() }
