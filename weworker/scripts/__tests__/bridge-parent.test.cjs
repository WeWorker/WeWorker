const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { fork, spawnSync } = require('node:child_process')
const { once } = require('node:events')
const guard = path.resolve(__dirname, '../bridge-parent.cjs')
test('desktop Bridge preload refuses a missing parent channel', () => {
  const result = spawnSync(process.execPath, ['--require', guard, '-e', 'process.exit(0)'], { encoding: 'utf8', windowsHide: true })
  assert.notEqual(result.status, 0)
  assert.match(result.stderr, /requires its parent IPC channel/)
})
test('real child shuts down through its cleanup handler when parent IPC closes', { timeout: 12000 }, async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bridge-parent-'))
  const script = path.join(root, 'bridge.cjs'), marker = path.join(root, 'stopped')
  fs.writeFileSync(script, `process.once('SIGTERM',()=>{require('fs').writeFileSync(${JSON.stringify(marker)},'clean');process.exit(0)});setInterval(()=>{},1000);process.send('ready');`)
  const child = fork(script, { execArgv: ['--require', guard], stdio: ['ignore', 'pipe', 'pipe', 'ipc'], windowsHide: true })
  t.after(() => { child.kill(); fs.rmSync(root, { recursive: true, force: true }) })
  await once(child, 'message')
  const exited = once(child, 'exit')
  child.disconnect()
  assert.equal((await exited)[0], 0)
  assert.equal(fs.readFileSync(marker, 'utf8'), 'clean')
})
